"""Makes right-sized copies of every comic panel and writes story/art-widths.js.

Run after adding or replacing panel art:  python story/build-art-widths.py
For each image used in panels.js (plus the cover), writes <name>-800.webp and,
when the original is wider than 1400px, <name>-1400.webp next to it. A variant is
rebuilt whenever the original is newer than it.
"""
import json, os, re

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, "..", "art", "story", "chibi")
EXTRA = ["hero-c2.webp"]  # the cover image on index.html

panels = open(os.path.join(HERE, "panels.js"), encoding="utf-8").read()
files = sorted(set(re.findall(r'"art":\s*"([^"]+\.webp)"', panels)) | set(EXTRA))

sizes = {}
for name in files:
    src = os.path.join(ART, name)
    if not os.path.exists(src):
        print("missing", name)
        continue
    im = Image.open(src)
    w, h = im.size
    variants = {}
    for target in (800, 1400):
        if w <= target:
            continue
        out_name = name[:-5] + f"-{target}.webp"
        out = os.path.join(ART, out_name)
        if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(src):
            im.convert("RGB").resize((target, round(h * target / w)), Image.LANCZOS).save(out, "WEBP", quality=80, method=6)
        variants[str(target)] = out_name
    sizes[name] = {"w": w, "h": h, "variants": variants}

with open(os.path.join(HERE, "art-widths.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by story/build-art-widths.py: original size and smaller variants per panel image.\n")
    f.write("export const ART_SIZES = " + json.dumps(sizes, separators=(",", ":")) + ";\n")
print(len(sizes), "images")
